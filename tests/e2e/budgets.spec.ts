import { _electron as electron, expect, test } from "@playwright/test";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
import { join, resolve } from "node:path";
import { MoguriSdk } from "../../packages/sdk/src/index.ts";
import { setupFixture } from "../fixture.ts";

const require = createRequire(import.meta.url);
test.skip(process.platform !== "darwin", "Budget UI execution is qualified on macOS.");
test("desktop applies warned estimate-based caps, preserves hard policy through defaults and shows actual cumulative roles", async () => {
  const fixture = await setupFixture({ maxOutputTokens: 128 }), sdk = await new MoguriSdk(fixture.service.connection).ready();
  await fixture.configure();
  const app = await electron.launch({ executablePath: process.env.MOGURI_TEST_APP ?? require("electron"), args: process.env.MOGURI_TEST_APP ? [] : ["."], env: { ...process.env, MOGURI_STATE_DIR: join(fixture.directory, "state"), MOGURI_TEST_WINDOW: "hidden" } });
  try {
    const page = await app.firstWindow(), failures: string[] = [];
    page.on("pageerror", (error) => failures.push(error.message));
    const composer = page.getByRole("form", { name: "Message composer" }), prompt = page.getByLabel("Prompt", { exact: true });
    await prompt.fill("Generated desktop finite budget.");
    await expect.poll(() => fixture.session().draft.text).toBe("Generated desktop finite budget.");
    const input = (await sdk.sessions.context(fixture.sessionId)).context.estimatedTokens;
    await composer.getByRole("button", { name: "Budget and usage", exact: true }).click();
    const menu = page.getByRole("dialog", { name: "Budget and usage", exact: true });
    await menu.getByRole("button", { name: "View usage and limits...", exact: true }).click();
    const controls = menu.getByRole("region", { name: "Session budget controls", exact: true });
    await controls.getByLabel("session budget mode", { exact: true }).selectOption("limited");
    await controls.getByLabel("session token cap", { exact: true }).fill(String(Math.ceil(input) + 16));
    await expect(controls.getByLabel("session USD cap", { exact: true })).toBeDisabled();
    await expect(controls.getByRole("button", { name: "Save session budget", exact: true })).toBeDisabled();
    await controls.getByText("I accept estimate-based accounting and interruption risk.", { exact: true }).click();
    await controls.getByRole("button", { name: "Save session budget", exact: true }).click();
    await expect(controls).toContainText("Session budget saved.");
    expect(fixture.session().controls.budget.kind).toBe("limited");
    expect(fixture.requests.length).toBe(0);
    await mkdir(resolve(".moguri/artifacts"), { recursive: true });
    await page.screenshot({ path: resolve(".moguri/artifacts/estimated-budget-desktop.png") });
    await page.keyboard.press("Escape");
    await composer.getByRole("button", { name: "Send", exact: true }).click();
    await expect.poll(() => fixture.session().status).toBe("completed");
    expect(fixture.requests[0]?.max_tokens ?? fixture.requests[0]?.max_completion_tokens).toBe(16);
    await page.getByRole("navigation", { name: "Projects and sessions" }).getByRole("button", { name: "Dashboard", exact: true }).click();
    const dashboard = page.getByRole("region", { name: "Profile usage dashboard", exact: true });
    await expect(dashboard).toContainText("42");
    await expect(dashboard).toContainText("solver");
    await page.getByRole("button", { name: "Settings", exact: true }).click();
    await page.getByRole("navigation", { name: "Settings categories" }).getByRole("button", { name: "Budgets", exact: true }).click();
    const policy = page.getByRole("region", { name: "Profile budget policy", exact: true });
    await policy.getByLabel("profile budget mode", { exact: true }).selectOption("limited");
    await policy.getByLabel("profile token cap", { exact: true }).fill("1");
    await policy.getByText("I accept estimate-based accounting and interruption risk.", { exact: true }).click();
    await policy.getByRole("button", { name: "Save profile budget policy", exact: true }).click();
    await expect(policy).toContainText("Profile policy saved.");
    await page.getByRole("button", { name: "Restore all defaults", exact: true }).click();
    await expect.poll(() => sdk.getState().snapshot!.budgetPolicy.limit?.tokens).toBe(1);
    await page.getByRole("button", { name: "Back to session", exact: true }).click();
    await prompt.fill("Generated request stopped before another model call.");
    await composer.getByRole("button", { name: "Send", exact: true }).click();
    await expect.poll(() => fixture.session().status).toBe("partial");
    expect(fixture.requests.length).toBe(1);
    expect(fixture.service.controller.snapshot().artifacts.some((artifact) => artifact.origin === "checkpoint")).toBe(true);
    await page.getByRole("navigation", { name: "Projects and sessions" }).getByRole("button", { name: "Dashboard", exact: true }).click();
    await expect(dashboard).toContainText("Profile hard policy");
    await dashboard.getByText("Filters", { exact: true }).click();
    await dashboard.getByLabel("Usage role filter", { exact: true }).selectOption("solver");
    await expect(dashboard).toContainText("42");
    await dashboard.getByText("Filters", { exact: true }).click();
    await dashboard.getByRole("heading", { name: "Usage dashboard", exact: true }).scrollIntoViewIfNeeded();
    await page.setViewportSize({ width: 900, height: 740 });
    await page.screenshot({ path: resolve(".moguri/artifacts/budget-dashboard-compact.png") });
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
    expect(failures).toEqual([]);
  } finally { await app.close(); sdk.disconnect(); await fixture.close(); }
});
